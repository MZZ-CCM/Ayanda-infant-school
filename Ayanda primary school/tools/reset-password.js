#!/usr/bin/env node
/* ==========================================================================
   Issue a one-time password
   --------------------------------------------------------------------------
   For a colleague who has forgotten theirs, or for the Head Teacher's account
   on a fresh install. It is shown once and marked must-change, so it stops
   working the moment it is used.

   Generated by default. Give one as a second argument to choose it instead —
   which is often easier when it has to be read down a telephone. Either way
   the holder replaces it at their first sign-in.

       node tools/reset-password.js head@ayandainfantschool.com
       node tools/reset-password.js head@ayandainfantschool.com marula-hill-42
       AYANDA_DB=/path/to/ayanda.db node tools/reset-password.js someone@…

   Any session that person already had is destroyed, so if the reason for the
   reset is that somebody else had their password, this ends that too.
   ========================================================================== */

const path = require("node:path");
const fs = require("node:fs");

const ROOT = path.resolve(__dirname, "..");
const DB_FILE = process.env.AYANDA_DB || path.join(ROOT, "server", "data", "ayanda.db");

const email = (process.argv[2] || "").trim();
const chosen = (process.argv[3] || "").trim();
if (!email) {
  console.error("\n  Which account?  node tools/reset-password.js <email> [password]\n");
  process.exit(1);
}
if (!fs.existsSync(DB_FILE)) {
  console.error(`\n  No database at ${DB_FILE}.`);
  console.error("  Start the server once to create it, or set AYANDA_DB to where it lives.\n");
  process.exit(1);
}

const db = require(path.join(ROOT, "server", "db.js"));
const auth = require(path.join(ROOT, "server", "auth.js"));

db.open(DB_FILE);

/* Staff or a guardian on the family portal — both hold an account here, and
   both can lose a password on a Sunday night. */
const found = auth.accountByEmail(email);
if (!found) {
  console.error(`\n  No account here uses ${email}.`);
  const staffEmails = db.all("staff").filter(s => s.active).map(s => s.email).filter(Boolean);
  const familyEmails = db.all("guardians").filter(g => g.active).map(g => g.email).filter(Boolean);
  if (staffEmails.length) console.error("  Staff accounts:\n" + staffEmails.map(e => "    " + e).join("\n"));
  if (familyEmails.length) console.error(`  Family accounts: ${familyEmails.length} — try the portal's Family portal page.`);
  console.error("");
  process.exit(1);
}
const account = found.account;

if (chosen) {
  const problem = auth.passwordProblem(chosen);
  if (problem) { console.error(`\n  ${problem}\n`); process.exit(1); }
}
const password = chosen || auth.temporaryPassword();
auth.setPassword(account.id, password, { mustChange: true, check: false });
auth.destroyAllSessions(account.id);
db.put("audit", `au_${Date.now().toString(36)}`, {
  id: `au_${Date.now().toString(36)}`, at: db.now(), by: null,
  action: `One-time password issued for ${account.name || `${account.first} ${account.last}`} from the command line`,
}, null);

const name = found.kind === "family"
  ? `${account.name} (family portal)`
  : `${account.title || ""} ${account.first} ${account.last}`.trim();
console.log(`
  One-time password for ${name}
  ${"—".repeat(28 + name.length)}

    email     ${account.email}
    password  ${password}

  Shown once and not stored anywhere in readable form. Hand it over in person
  or by telephone — not by email, which is where passwords go to be forgotten
  about. They will be asked to set their own the first time they sign in, and
  this one stops working at that point.

  Any session that account already had has been signed out.
`);
